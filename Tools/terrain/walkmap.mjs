// Where animals can go: a coarse grid over the island for roaming wildlife (WRWildlife), from the same island model as
// spawns.mjs: the heightmap, the layout's camps and boss sites, the caves and hazard cells in Data/island_dressing.json.
// Written to Data/island_walk.json, one letter per cell, read at server start:
//   ~ sea, x nobody (boss arenas, mini-boss sites, caves), # too steep or hazardous to walk (flyers cross it),
//   g ground, f open flat ground (where grazers feed), w ground by the shore
//   node Tools/terrain/walkmap.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const SIZE = 4033, UNITS_PER_METRE = 32, HALF = (SIZE - 1) * 100 / 2;
const CELL_M = 32;                    // metres per cell
const CELLS = Math.floor((SIZE - 1) / CELL_M);
const raw = fs.readFileSync(path.join(root, "Art/Terrain/island_height.r16"));
const layout = JSON.parse(fs.readFileSync(path.join(root, "Docs/terrain/layout_proposal.json"), "utf8"));
const dressing = JSON.parse(fs.readFileSync(path.join(root, "Data/island_dressing.json"), "utf8"));
const spawns = JSON.parse(fs.readFileSync(path.join(root, "Data/island_spawns.json"), "utf8"));
const creatures = JSON.parse(fs.readFileSync(path.join(root, "Data/creatures.json"), "utf8")).creatures;

const h = (x, y) => {
	const i = Math.max(0, Math.min(SIZE - 1, Math.round(x))), j = Math.max(0, Math.min(SIZE - 1, Math.round(y)));
	return (raw.readUInt16LE((j * SIZE + i) * 2) - 32768) / UNITS_PER_METRE;
};
const slope = (x, y) => Math.max(Math.abs(h(x + 2, y) - h(x - 2, y)), Math.abs(h(x, y + 2) - h(x, y - 2))) / 4;
const toMetres = (cm) => (cm + HALF) / 100;

// As spawns.mjs: boss arenas, mini-boss sites and caves stay clear; keep 12 m from lava and slick ice.
const keepOut = [
	...layout.bosses.map(b => ({ x: b.x, y: b.y, r: 220 })),
	...layout.miniBosses.map(b => ({ x: b.x, y: b.y, r: 120 })),
	...dressing.caves.map(c => ({ x: toMetres(c.x), y: toMetres(c.y), r: 70 })),
];
const HAZ = dressing.hazards.cell / 100;
const hazard = new Set();
for (const kind of ["lava", "ice"]) {
	const a = dressing.hazards[kind];
	for (let i = 0; i < a.length; i += 3) hazard.add(`${Math.round(toMetres(a[i]) / HAZ)},${Math.round(toMetres(a[i + 1]) / HAZ)}`);
}
const nearHazard = (x, y) => {
	for (let dy = -2; dy <= 2; dy++) for (let dx = -2; dx <= 2; dx++) if (hazard.has(`${Math.round(x / HAZ) + dx},${Math.round(y / HAZ) + dy}`)) return true;
	return false;
};

// Walking, not where to set a pack down (spawns.mjs keeps sites under 0.45): the engine's walkable limit is about 1.0.
const MAX_SLOPE = 0.8, FLAT_SLOPE = 0.2, SEA_Z = 3, SHORE_M = 48;
const grid = [];
for (let cy = 0; cy < CELLS; cy++) {
	let row = "";
	for (let cx = 0; cx < CELLS; cx++) {
		const mx = (cx + 0.5) * CELL_M, my = (cy + 0.5) * CELL_M;
		if (keepOut.some(k => Math.hypot(k.x - mx, k.y - my) < k.r)) { row += "x"; continue; }
		let samples = 0, sea = 0, bad = 0, steep = 0;
		for (let oy = -12; oy <= 12; oy += 8) for (let ox = -12; ox <= 12; ox += 8) {
			const x = mx + ox, y = my + oy;
			samples++;
			if (h(x, y) < SEA_Z) { sea++; continue; }
			const s = slope(x, y);
			steep += s;
			if (s > MAX_SLOPE || nearHazard(x, y)) bad++;
		}
		if (sea > samples / 2) row += "~";
		else if (sea > 0 || bad > samples * 0.3) row += "#";
		else {
			let shore = false;
			for (const [dx, dy] of [[SHORE_M, 0], [-SHORE_M, 0], [0, SHORE_M], [0, -SHORE_M]]) shore ||= h(mx + dx, my + dy) < SEA_Z;
			row += shore ? "w" : steep / samples < FLAT_SLOPE ? "f" : "g";
		}
	}
	grid.push(row);
}

// How far each kind of creature may roam, as in spawns.mjs: its elevation band (metres from the ridge) and its distance
// from a player camp (metres). World X = 0 is the ridge.
const out = {
	_comment: "Generated by Tools/terrain/walkmap.mjs from the heightmap, layout and dressing. Roaming wildlife's map (WRWildlife): cell cm, origin = the world position of cell 0,0's corner, rows[y][x]: ~ sea, x nobody (arenas, caves), # steep or hazard (flyers cross it), g ground, f flat open ground (feeding), w ground by the shore. bands (metres from the ridge at X = 0) and campGap (metres) keep each kind where spawns.mjs put it.",
	map: spawns.map,
	cell: CELL_M * 100,
	origin: -HALF,
	bands: { lowland: [900, 1900], midland: [450, 1050], highland: [140, 620] },
	campGap: { passive: 90, neutral: 160, aggressive: 280 },
	camps: layout.spawns.map(s => ({ x: Math.round(s.x * 100 - HALF), y: Math.round(s.y * 100 - HALF) })),
	rows: grid,
};
fs.writeFileSync(path.join(root, "Data/island_walk.json"), JSON.stringify(out, null, 1).replace(/\n {2,}/g, " ").replace(/\[\n /g, "[").replace(/\n \]/g, "]").replace(/" "/g, '",\n"').replace(/", "/g, '",\n  "'));

// What each kind gets, and whether the sites it starts at are on ground it can use.
const count = {};
for (const row of grid) for (const c of row) count[c] = (count[c] || 0) + 1;
console.log(`${CELLS} x ${CELLS} cells:`, Object.entries(count).map(([k, v]) => `${k} ${v}`).join(", "));
const cellAt = (xCm, yCm) => [Math.floor((xCm + HALF) / (CELL_M * 100)), Math.floor((yCm + HALF) / (CELL_M * 100))];
for (const c of creatures) {
	const own = spawns.sites.filter(s => s.creature === c.id);
	if (!own.length) continue;
	const [near, far] = out.bands[c.tier] || out.bands.midland;
	const gap = out.campGap[c.behavior] || 160;
	const flyer = c.archetype === "flyer";
	const allowed = (cx, cy) => {
		const ch = grid[cy]?.[cx];
		if (!ch || ch === "~" || ch === "x" || (ch === "#" && !flyer)) return false;
		const xCm = (cx + 0.5) * CELL_M * 100 - HALF, yCm = (cy + 0.5) * CELL_M * 100 - HALF;
		if (c.biome === "volcanic" ? xCm >= 0 : xCm <= 0) return false;
		const d = Math.abs(xCm) / 100;
		if (d < near || d > far) return false;
		return !out.camps.some(k => Math.hypot(k.x - xCm, k.y - yCm) / 100 < gap);
	};
	let cells = 0;
	for (let y = 0; y < CELLS; y++) for (let x = 0; x < CELLS; x++) if (allowed(x, y)) cells++;
	const onIt = own.filter(s => { const [x, y] = cellAt(s.x, s.y); return allowed(x, y); }).length;
	// The largest connected piece of what it may walk on.
	const seen = new Set();
	let largest = 0;
	for (let y = 0; y < CELLS; y++) for (let x = 0; x < CELLS; x++) {
		if (!allowed(x, y) || seen.has(y * CELLS + x)) continue;
		let size = 0;
		const stack = [[x, y]];
		seen.add(y * CELLS + x);
		while (stack.length) {
			const [a, b] = stack.pop();
			size++;
			for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) if ((dx || dy) && allowed(a + dx, b + dy) && !seen.has((b + dy) * CELLS + a + dx)) { seen.add((b + dy) * CELLS + a + dx); stack.push([a + dx, b + dy]); }
		}
		largest = Math.max(largest, size);
	}
	console.log(`${c.id.padEnd(15)} ${String(cells).padStart(5)} cells (${(cells * CELL_M * CELL_M / 1e6).toFixed(1)} km2), largest piece ${String(largest).padStart(5)}, ${onIt}/${own.length} sites on them`);
}
