// Writes Data/preload_code.json: every asset the C++ loads by a literal path (TEXT("/Game/...")), so the background
// preload (UWRPreloadSubsystem, Data/preload.json "scan") brings them in at map start instead of the frame that first
// needs one (cooks/cookpass-performance.md 3.9). Paths built with a format string (a "%") can't be known here and are
// left out; maps are left out. Run after adding a LoadObject path:  node Tools/perf/scan_code_assets.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const src = path.join(root, 'Source', 'Wildreach');
const found = new Set();
const literal = /TEXT\("(\/Game\/[^"%]+)"\)/g;

function walk(dir) {
	for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
		const p = path.join(dir, e.name);
		if (e.isDirectory()) {
			if (e.name !== 'Tests') walk(p);
		} else if (/\.(cpp|h)$/.test(e.name)) {
			const text = fs.readFileSync(p, 'utf8');
			for (const m of text.matchAll(literal)) {
				const s = m[1];
				// A whole object path or package path only (not a folder prefix such as "/Game/Props/").
				if (s.startsWith('/Game/Maps/') || s.endsWith('/')) continue;
				found.add(s);
			}
		}
	}
}
walk(src);
const paths = [...found].sort();
const out = {
	_comment: 'Generated by Tools/perf/scan_code_assets.mjs from the literal /Game/ paths in Source/Wildreach (not by hand). Preloaded at map start through Data/preload.json "scan"; paths whose package is missing (a Fab pack not installed) are skipped at runtime.',
	paths,
};
fs.writeFileSync(path.join(root, 'Data', 'preload_code.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`preload_code.json: ${paths.length} paths`);
